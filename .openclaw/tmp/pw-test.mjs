import pw from '/Users/albertolive/.npm/_npx/9833c18b2d85bc59/node_modules/playwright/index.js';
const { chromium } = pw;
const b = await chromium.launch({ executablePath: process.env.CHROME_BIN });
const ctx = await b.newContext({ viewport: { width: 1280, height: 720 } });
const p = await ctx.newPage();
await p.goto('https://eltempsavui.cat', { waitUntil: 'load', timeout: 45000 });
await p.waitForTimeout(2500);
const title = await p.title();
const nav = await p.$$eval('nav a, header a', els => els.slice(0,12).map(e => ({t: e.textContent.trim().slice(0,30), h: e.getAttribute('href')})));
await p.screenshot({ path: '.openclaw/tmp/pw-test.png' });
console.log(JSON.stringify({ title, nav }, null, 1));
await b.close();
